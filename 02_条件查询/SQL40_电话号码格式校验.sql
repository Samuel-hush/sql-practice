-- ================================================
-- 题目：电话号码格式校验
-- 考察点：REGEXP 正则
-- ================================================
-- 要求：从 contacts 表查出合法电话号码：10 位数字、首位非 0、可带 - 分隔。
-- 涉及表：contacts（id, name, phone_number）
-- 思路：
--   1. 用 REGEXP 按模式匹配
--   2. ^ 开头、$ 结尾、[0-9]{n} 表示 n 个数字、-? 表示可选的 -
-- 笔记/心得：
--   · REGEXP 里的 {} 是数量、[] 是字符集，跟 LIKE 的通配符不一样
-- ================================================

SELECT id, name, phone_number
FROM contacts
WHERE phone_number REGEXP '^[1-9][0-9]{2}-?[0-9]{3}-?[0-9]{4}$'
ORDER BY id;
